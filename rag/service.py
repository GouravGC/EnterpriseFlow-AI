
import logging
from pathlib import Path
from typing import Any

import chromadb
import requests
from langchain_text_splitters import RecursiveCharacterTextSplitter
from pypdf import PdfReader

from config import settings


logger = logging.getLogger(__name__)

OPENROUTER_EMBEDDINGS_URL = (
    "https://openrouter.ai/api/v1/embeddings"
)

# Keep batches modest to avoid oversized requests.
EMBEDDING_BATCH_SIZE = 8
MAX_DOCUMENT_BYTES = 10 * 1024 * 1024


class RAGService:
    """Document ingestion, remote embeddings, and ChromaDB retrieval."""

    def __init__(self) -> None:
        self.api_key = settings.openrouter_api_key.strip()
        self.embedding_model = (
            settings.openrouter_embedding_model.strip()
            or "nvidia/nemotron-3.5-embed-1b:free"
        )

        chroma_path = Path(settings.chroma_path).resolve()
        chroma_path.mkdir(parents=True, exist_ok=True)

        self.client = chromadb.PersistentClient(
            path=str(chroma_path)
        )

        # A new collection prevents mixing old Hugging Face vectors
        # with vectors generated by the OpenRouter embedding model.
        self.collection = self.client.get_or_create_collection(
            name="enterpriseflow_openrouter_embeddings",
            metadata={"hnsw:space": "cosine"},
        )

        self.text_splitter = RecursiveCharacterTextSplitter(
            chunk_size=1000,
            chunk_overlap=150,
            separators=["\n\n", "\n", ". ", " ", ""],
        )

        self.http = requests.Session()
        self.http.headers.update(
            {
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json",
                "X-Title": "EnterpriseFlow AI",
            }
        )

        logger.info(
            "RAG service initialized. Embedding model: %s",
            self.embedding_model,
        )

    def _embed_batch(self, texts: list[str]) -> list[list[float]]:
        """Generate embeddings for a batch of texts via OpenRouter."""

        if not self.api_key:
            raise RuntimeError(
                "OPENROUTER_API_KEY is missing. "
                "Configure it in your .env file."
            )

        if not texts:
            return []

        response = self.http.post(
            OPENROUTER_EMBEDDINGS_URL,
            json={
                "model": self.embedding_model,
                "input": texts,
                "encoding_format": "float",
            },
            timeout=(10, 90),
        )

        if not response.ok:
            # Keep the provider's useful error detail for local logs.
            try:
                provider_detail = response.json()
            except ValueError:
                provider_detail = response.text[:1000]

            logger.error(
                "OpenRouter embeddings failed: HTTP %s; %s",
                response.status_code,
                provider_detail,
            )

            if response.status_code == 401:
                message = (
                    "OpenRouter rejected the API key. "
                    "Check OPENROUTER_API_KEY."
                )
            elif response.status_code == 402:
                message = (
                    "The embedding request was rejected for billing "
                    "or account-credit reasons. Verify the selected "
                    "model's current free access in OpenRouter."
                )
            elif response.status_code == 429:
                message = (
                    "OpenRouter rate limit reached. Wait before "
                    "retrying the document upload."
                )
            else:
                message = (
                    f"OpenRouter embedding request failed "
                    f"with HTTP {response.status_code}. "
                    "Check the API terminal logs."
                )

            raise RuntimeError(message)

        try:
            payload = response.json()
            items = payload["data"]
            items = sorted(
                items,
                key=lambda item: item.get("index", 0),
            )
            vectors = [
                item["embedding"]
                for item in items
            ]
        except (ValueError, KeyError, TypeError) as exc:
            raise RuntimeError(
                "OpenRouter returned an unexpected embedding response."
            ) from exc

        if len(vectors) != len(texts):
            raise RuntimeError(
                "Embedding count did not match the input text count."
            )

        for vector in vectors:
            if not isinstance(vector, list) or not vector:
                raise RuntimeError(
                    "OpenRouter returned an empty or invalid embedding."
                )

            if not all(
                isinstance(value, (int, float))
                for value in vector
            ):
                raise RuntimeError(
                    "OpenRouter returned non-numeric embedding values."
                )

        # ChromaDB requires consistent vector dimensions within
        # a collection. Validate before writing.
        dimensions = {len(vector) for vector in vectors}
        if len(dimensions) != 1:
            raise RuntimeError(
                "OpenRouter returned inconsistent embedding dimensions."
            )

        return vectors

    def _embed(self, text: str) -> list[float]:
        """Embed a single string, useful for queries and diagnostics."""

        return self._embed_batch([text])[0]

    def _embed_many(
        self,
        texts: list[str],
    ) -> list[list[float]]:
        """Embed many texts in bounded batches, preserving order."""

        vectors: list[list[float]] = []

        for start in range(0, len(texts), EMBEDDING_BATCH_SIZE):
            batch = texts[
                start : start + EMBEDDING_BATCH_SIZE
            ]
            vectors.extend(self._embed_batch(batch))

        return vectors

    @staticmethod
    def _extract_document_pages(
        filename: str,
        content: bytes,
    ) -> list[dict[str, Any]]:
        """Extract page-aware text from PDF, TXT, or Markdown files."""

        suffix = Path(filename).suffix.lower()

        if suffix == ".pdf":
            import io

            try:
                reader = PdfReader(io.BytesIO(content))
                pages: list[dict[str, Any]] = []

                for page_number, page in enumerate(reader.pages, start=1):
                    text = (page.extract_text() or "").strip()

                    if text:
                        pages.append(
                            {
                                "text": text,
                                "source": filename,
                                "page": page_number,
                            }
                        )

                if not pages:
                    raise ValueError(
                        "No extractable text was found in the PDF. "
                        "It may be scanned or image-only."
                    )

                return pages

            except ValueError:
                raise
            except Exception as exc:
                raise ValueError(
                    "Could not read this PDF. Check that it is valid "
                    "and not password-protected."
                ) from exc

        if suffix in {".txt", ".md", ".markdown"}:
            try:
                text = content.decode("utf-8-sig").strip()
            except UnicodeDecodeError as exc:
                raise ValueError(
                    "The text document must use UTF-8 encoding."
                ) from exc

            if not text:
                raise ValueError(
                    "The uploaded document contains no text."
                )

            return [
                {
                    "text": text,
                    "source": filename,
                    "page": None,
                }
            ]

        raise ValueError(
            "Unsupported file type. Upload PDF, TXT, or Markdown."
        )

    def add_document(
        self,
        filename: str,
        content: bytes,
    ) -> int:
        """Extract, chunk, embed, and index a document."""

        if not filename:
            raise ValueError("A filename is required.")

        if not content:
            raise ValueError("The uploaded document is empty.")

        if len(content) > MAX_DOCUMENT_BYTES:
            raise ValueError(
                "File exceeds the 10 MB upload limit."
            )

        pages = self._extract_document_pages(filename, content)

        chunks: list[str] = []
        metadatas: list[dict[str, Any]] = []

        for page in pages:
            page_chunks = self.text_splitter.split_text(
                page["text"]
            )

            for chunk in page_chunks:
                if not chunk.strip():
                    continue

                chunks.append(chunk)
                metadatas.append(
                    {
                        "source": page["source"],
                        "page": page["page"] or 0,
                    }
                )

        if not chunks:
            raise ValueError(
                "No searchable text chunks could be created."
            )

        # Generate every vector before writing so an embedding
        # failure does not leave a partially indexed document.
        embeddings = self._embed_many(chunks)

        # Use deterministic IDs so uploading the same file again
        # replaces that file's previous chunks instead of duplicating.
        import hashlib

        file_key = hashlib.sha256(
            filename.encode("utf-8")
        ).hexdigest()[:16]

        ids = [
            f"{file_key}_{index}"
            for index in range(len(chunks))
        ]

        existing = self.collection.get(
            where={"source": filename},
            include=["metadatas"],
        )
        existing_ids = existing.get("ids", [])

        if existing_ids:
            self.collection.delete(ids=existing_ids)

        self.collection.add(
            ids=ids,
            documents=chunks,
            metadatas=metadatas,
            embeddings=embeddings,
        )

        logger.info(
            "Indexed '%s': %d chunks using %s",
            filename,
            len(chunks),
            self.embedding_model,
        )

        return len(chunks)

    def retrieve(
        self,
        question: str,
        top_k: int = 4,
    ) -> list[dict[str, Any]]:
        """Retrieve the most relevant document chunks for a question."""

        question = question.strip()
        if not question:
            return []

        if top_k < 1:
            return []

        if self.collection.count() == 0:
            return []

        query_embedding = self._embed(question)

        result = self.collection.query(
            query_embeddings=[query_embedding],
            n_results=min(top_k, self.collection.count()),
            include=["documents", "metadatas", "distances"],
        )

        documents = (result.get("documents") or [[]])[0]
        metadatas = (result.get("metadatas") or [[]])[0]
        distances = (result.get("distances") or [[]])[0]

        retrieved: list[dict[str, Any]] = []

        for index, document in enumerate(documents):
            metadata = (
                metadatas[index]
                if index < len(metadatas) and metadatas[index]
                else {}
            )
            page_value = metadata.get("page", 0)

            retrieved.append(
                {
                    "text": document or "",
                    "source": metadata.get(
                        "source",
                        "Unknown document",
                    ),
                    "page": page_value or None,
                    "distance": (
                        distances[index]
                        if index < len(distances)
                        else None
                    ),
                }
            )

        return retrieved

    def chunk_count(self) -> int:
        """Return the total number of indexed chunks."""

        return self.collection.count()
